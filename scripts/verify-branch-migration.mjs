/**
 * The seed is a closed set of literals defined in this file, never external
 * input. Emitting SQL literals rather than bound parameters is deliberate:
 * Prisma binds parameters as `text`, and PostgreSQL will not assign `text` to a
 * UUID or enum column in an INSERT target. A quoted literal stays `unknown`, so
 * the target column's own type resolves it without per-column casts.
 */
function sqlLiteral(value) {
  if (value === null) return "NULL";
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  if (typeof value === "number") return String(value);
  return `'${String(value).replaceAll("'", "''")}'`;
}

async function insert(db, table, values) {
  const columns = Object.keys(values);
  await db.$executeRawUnsafe(
    `INSERT INTO "${table}" (${columns.map((column) => `"${column}"`).join(", ")}) ` +
      `VALUES (${columns.map((column) => sqlLiteral(values[column])).join(", ")})`
  );
}

async function scalar(db, sql, ...parameters) {
  const [row] = await db.$queryRawUnsafe(sql, ...parameters);
  assert.ok(row, `query returned no row: ${sql}`);
  return row.value;
}

