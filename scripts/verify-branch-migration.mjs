async function collectState(db, tables) {
  const counts = {};
  const idsByTable = {};
  for (const table of tables) {
    const rows = await db.$queryRawUnsafe(`SELECT "id"::text AS id FROM "${table}" ORDER BY "id"`);
    counts[table] = rows.length;
    idsByTable[table] = rows.map((row) => row.id);
  }

  const sums = {};
  for (const probe of SUM_PROBES) {
    sums[probe.label] = await scalar(db, probe.sql);
  }
  return { counts, idsByTable, sums };
}

async function appliedMigrations(db) {
  const rows = await db.$queryRawUnsafe(
    'SELECT "migration_name"::text AS name FROM "_prisma_migrations" ' +
      'WHERE "finished_at" IS NOT NULL ORDER BY "migration_name"'
  );
  return rows.map((row) => row.name);
}

async function columnCount(db, table, column) {
  return scalar(
    db,
    "SELECT COUNT(*)::int AS value FROM information_schema.columns " +
      "WHERE table_schema = current_schema() AND table_name = $1 AND column_name = $2",
    table,
    column
  );
}

async function branchesFor(db, tenantId) {
  return db.$queryRawUnsafe(
    'SELECT "id"::text AS id, "name" AS name, "is_active" AS "isActive", ' +
      '"address" AS address, "phone" AS phone ' +
      'FROM "branch" WHERE "tenant_id" = $1::uuid ORDER BY "created_at", "id"',
    tenantId
  );
}

async function deployMigrations(label, { schema, cwd }) {
  const result = spawnSync(
    process.execPath,
    [databaseRequire.resolve("prisma/build/index.js"), "migrate", "deploy", "--schema", schema],
    {
      cwd,
      env: { ...process.env, DATABASE_URL: drillDatabaseUrl },
      encoding: "utf8",
    }
  );
  if (result.status !== 0) {
    throw new Error(
      `${label}: prisma migrate deploy failed (exit ${result.status}).\n` +
        `${result.stdout ?? ""}${result.stderr ?? ""}`
    );
  }
}

async function prepareHistoricalMigrationTree() {
  const names = (await readdir(migrationsDir, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  const cutoff = names.indexOf(MB_001);
  assert.ok(cutoff > 0, `${MB_001} must exist and have earlier migrations`);
  for (const migration of MB_MIGRATIONS) {
    assert.ok(names.includes(migration), `required migration ${migration} is missing`);
  }

  const historical = names.slice(0, cutoff);
  assert.ok(historical.length > 0, "there must be migrations older than MB-001");
  for (const migration of historical) {
    assert.ok(migration < MB_001, `${migration} must not be part of the historical migration tree`);
  }

  const tree = await mkdtemp(path.join(tmpdir(), "newsaas-branch-drill-tree-"));
  scratchDirs.push(tree);
  await mkdir(path.join(tree, "migrations"));
  await copyFile(schemaPath, path.join(tree, "schema.prisma"));
  await copyFile(
    path.join(migrationsDir, "migration_lock.toml"),
    path.join(tree, "migrations", "migration_lock.toml")
  );
  for (const migration of historical) {
    await cp(path.join(migrationsDir, migration), path.join(tree, "migrations", migration), {
      recursive: true,
    });
  }

  return {
    directory: tree,
    schema: path.join(tree, "schema.prisma"),
    historical,
    all: names,
  };
}

